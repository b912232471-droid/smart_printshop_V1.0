const currentLanguage = () => localStorage.getItem('lang') || 'zh-cn'
const orderedEntries = Object.entries(EN_TRANSLATIONS).sort((a, b) => b[0].length - a[0].length)

export const translateText = value => {
  if (currentLanguage() !== 'en' || typeof value !== 'string' || !/[\u3400-\u9fff]/.test(value)) return value
  return orderedEntries.reduce((result, [source, target]) => result.replaceAll(source, target), value)
}

const translateNode = node => {
  if (node.nodeType === Node.TEXT_NODE) {
    const nextValue = translateText(node.nodeValue)
    if (nextValue !== node.nodeValue) node.nodeValue = nextValue
    return
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return
  for (const attribute of ['placeholder', 'title', 'aria-label']) {
    const value = node.getAttribute(attribute)
    const translated = translateText(value)
    if (value && translated !== value) node.setAttribute(attribute, translated)
  }
  node.childNodes.forEach(translateNode)
}

export const installLanguageObserver = root => {
  if (currentLanguage() !== 'en' || !root) return () => {}
  translateNode(root)
  const observer = new MutationObserver(mutations => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') translateNode(mutation.target)
      else if (mutation.type === 'attributes') translateNode(mutation.target)
      else mutation.addedNodes.forEach(translateNode)
    }
  })
  observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'title', 'aria-label'] })
  return () => observer.disconnect()
}
